// tools/gen-asset-list.mjs
//
// Writes js/assetList.js: every image, sound, shader and font the game
// loads, so love.boot can preload them all before love.load runs (the
// browser can't load files synchronously the way LÖVE does).
//
// Found by scanning js/ for 'img/...', 'sound/...', 'shaders/...' and
// 'font/...' string literals. Run with `npm run assets` (npm run build
// does it too).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const found = { images: new Set(), sounds: new Set(), texts: new Set(), fonts: new Set() };
const patterns = {
  images: /['"`](img\/[^'"`$]+\.(?:png|jpg|jpeg))['"`]/g,
  sounds: /['"`](sound\/[^'"`$]+\.(?:wav|mp3|ogg))['"`]/g,
  texts: /['"`](shaders\/[^'"`$]+\.glsl)['"`]/g,
  fonts: /['"`](font\/[^'"`$]+\.(?:ttf|otf))['"`]/g,
};

function walk(dir, fn) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, fn);
    else fn(p);
  }
}

walk(path.join(root, 'js'), (file) => {
  if (!file.endsWith('.js') || file.endsWith('assetList.js')) return;
  const src = fs.readFileSync(file, 'utf8');
  for (const [kind, re] of Object.entries(patterns)) {
    for (const m of src.matchAll(re)) found[kind].add(m[1]);
  }
});

for (const set of Object.values(found)) {
  for (const p of [...set]) {
    if (!fs.existsSync(path.join(root, p))) {
      console.warn(`gen-asset-list: ${p} is referenced but doesn't exist — left out.`);
      set.delete(p);
    }
  }
}

const lists = Object.fromEntries(Object.entries(found).map(([k, v]) => [k, [...v].sort()]));
const out = `// js/assetList.js — generated by tools/gen-asset-list.mjs. Don't edit by hand.
export default ${JSON.stringify(lists, null, 2)};
`;
fs.writeFileSync(path.join(root, 'js/assetList.js'), out);
console.log(`gen-asset-list: ${lists.images.length} images, ${lists.sounds.length} sounds, ` +
  `${lists.texts.length} shaders, ${lists.fonts.length} fonts`);
